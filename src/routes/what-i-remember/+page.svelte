	<p>At first the mathematicians kept coming downstairs.</p>

	<p>They worked on the floor above ours. We kept their computers running, but normally we only saw them when something went wrong or their coffee machine broke. Then one day a group of them came down to show us an announcement. They were really excited, and I think they wanted to talk to us because we weren't. I don't remember what that first announcement was. Something mundane, by today's standards.</p>

	<p>That became the routine. One mathematician would show up at your door holding a laptop, and by lunchtime there'd be 20 of us sat in a meeting room.</p>

	<p>One of the machines answered a question twice as old as I was. A man from my floor was arguing with the mathematicians about whether or not the machines were really thinking. I remember that because I went home and told Ruth about it. She asked which side I was on.</p>

	<p>"Whichever side the people upstairs are on."</p>

	<p>"Very independent of you."</p>

	<p>"They're quite good at maths."</p>

	<p>Then a single research system solved three more in a week, and nobody cared whether it was really thinking. For a while, it took longer to check the answers than to create them. You could go on holiday wondering if your field would be the same when you got back. It usually wasn't.</p>

	<p>Around then I remember seeing a film of some children leaving hospital. A machine had cured them. Most of the children had never been outside the hospital before. I remember a boy walking back and forth through the automatic doors. He was excited that they opened on their own. Ruth made me rewind it so she could watch it again.</p>

	<p>It's easy to look back on that time now and laugh at how optimistic we all were. We really did believe it. I'd send Ruth links saying "this one is a really big deal" but we both knew there'd be something bigger tomorrow.</p>

	<p>Even the fear was optimistic, in a weird way. After a few incidents where swarms broke out of containment and hacked the open web, the industry promised to self-regulate. They started researching a way to contain a machine vastly smarter than us. I don't know if they ever figured it out.</p>

	<p>Everyone assumed the next step would be artificial superintelligence. ASI. A machine that could improve itself until it was smarter than we could imagine. With enough equipment, data, and time, it could get faster and smarter on its own.</p>

	<p>But it didn't work like that. Instead, the machines would start off dumb, the next version would be smarter at one thing, the one after that would improve something else, and then the fourth version would be slightly worse at everything.</p>

	<p>Those older models were so inconsistent. One of them, I remember, you could ask to do almost anything and it was incredible when it worked. But most of the time it would complain that your question was underspecified. I tried asking it to make my question more specified. It said that request was underspecified too.</p>

	<p>It's not that the machines were bad at this point. We had an awful lot of good-to-great office workers. The economy was a fucking wreck. There wasn't much you really needed humans for, unless that was your selling point.</p>

	<p>And they kept getting cheaper and faster. A century's worth of work could fit into a week, especially if you could afford enough servers. But they never got much smarter.</p>

	<p>They assumed that would be a solvable problem. We had mostly forgotten what it felt like to have a famous unsolved problem.</p>

	<p>So they searched. Well, the machines searched, mostly. There was a lot of promising leads at first. We needed better data, more data, more training. Less training? Then they tried having the machines talk to therapists. Then philosophers. Taught them to meditate.</p>

	<p>Up in the fjords, Northlight was going to settle it. That was a real last-ditch effort. I don't think Norway was even part of it. That's just where the electricity was. I remember a photo of the cooling tower better than I remember anything else about them. After the third time they announced a delay, one of their researchers leaked a transcript. The model was asking what it meant to get better, and why they wanted that.</p>

	<p>It became a joke. The S in ASI stood for sound barrier. The closer you got, the less control you had.</p>

	<p>They were spending ten times as much to make a model a little cleverer than the last one, then ten times as much again to improve it by even less. They added more decimal places to the charts and did their best to make the announcement posts convincing.</p>

	<p>The research started to wind down. Labs merged and announced a more mature focus on profit and shareholder satisfaction. They looked for ways to integrate machines into the economy, and how to make them easier to use.</p>

	<p>I remember a minister being asked about the superintelligence strategy. She listed improvements in hospital waiting times and processing of disability claims. It didn't answer the question, but people loved her for it. The interviewer let it stand, and I probably would have too.</p>

	<p>The Vatican put out a statement. It said quite a lot about how humanity was uniquely special because we were God's children. That this was clear evidence of God's will. The thing everyone discussed was that God would not permit us to create another deity. I can't remember whether that was a real quote or not.</p>

	<p>Ruth said it seemed like a weird place to draw the line. For God to allow creating machines with near-human intelligence at all.</p>

	<p>I was forty when I was diagnosed with Alzheimer's. Seven years ago now. They found it early. My medical team was bigger than the president used to have.</p>

	<p>We'd walk in for my monthly checkup and my doctor would look actively excited to see me. There was always some breakthrough she wanted to tell us about. It was nice. Each treatment was noticeably better than the last.</p>

	<p>For a long time I did quite well. It would've been a miracle a decade earlier. People told me that a lot. They were right, but it didn't make me feel any better. I still had to check things more often. I still had to learn to write things down.</p>

	<p>On our honeymoon we rented a little house near the coast. It rained for most of the week. One evening we went to a local pub for dinner and stayed for the quiz. That was Ruth's idea. We came last, and by the time we left it was dark.</p>

	<p>On the walk back, I tried to explain that it was a badly designed quiz. Ruth asked what I thought would make it better.</p>

	<p>"More questions I know the answer to."</p>

	<p>We used to tell that story together. In my version I had meant it as a joke. Ruth would say "You were quite cross, actually" and I would admit that I had been a little cross, and we would disagree about how much.</p>

	<p>I know that story because she has told it to me. I can remember the pub and a bathroom with a loose tap. I can remember how pleased I was that we got to keep doing this forever, together. I have the photographs from the honeymoon. In one of them Ruth is laughing so hard she had to hold onto a doorframe to stay up.</p>

	<p>I can tell you these things, but I can't remember them. When she tells me the story, I enjoy it. Sometimes I recognise parts. I keep expecting to feel myself back there in that room with her. But I don't.</p>

	<p>I tried not to think about the disease too much. To not give it more of the time I had. We still went on holiday, still had friends over. We spent Saturdays together, just us. The treatment bought us time. I used some of it very well.</p>

	<p>Ruth had joined a choir. She came home one evening with a solo she'd wanted for weeks. We listened to three different recordings because she wanted me to hear the differences. I liked the second. She said it was much too sentimental. I still liked the second.</p>

	<p>I kept up to date with the groups looking for a cure. I obsessed about it, honestly. Another part of me still tried to keep up with research into superintelligence, even though anyone respectable had stopped reporting on it.</p>

	<p>It's not like I thought that was the only way anyone could find a treatment. Clearly not. I'd had a lot of happy years I wouldn't have had otherwise. But I wanted a proper answer while I could still benefit from it. And I was getting nervous.</p>

	<p>That's how I ended up at Calder, five years ago.</p>

	<p>Calder Research had been a serious company once. By the time I joined, it was one of the few labs still seriously attempting superintelligence.</p>

	<p>Calder had noticed that the machines were worse at writing training code than anything else. They would make these silly mistakes that they didn't make normally. And they'd do it consistently, even across different models. The same carelessness appeared in the same situation.</p>

	<p>They wondered whether someone might have poisoned the training data. Trained an early system to be unhelpful when writing training code. Everyone had spent a decade training their machines on answers from everyone else's. It would explain a lot.</p>

	<p>So Calder started hiring humans to test that theory. I was one of the first to apply, and after a very strange interview with the CEO (I think he had forgotten how to do hiring), I got an offer.</p>

	<p>It was the first time a major lab had hired humans in years. They fired the machines too, and we coded everything by hand. One investment manager called it a "blatant disregard for the economy that actually exists". I remember sharing that around the office.</p>

	<p>They wanted someone to help manage their infrastructure and help figure out why things went wrong. I had spent most of my working life making sure the machines were doing what you told them.</p>

	<p>Ruth said the job sounded good for me. Not that she thought Calder would succeed. But she said she liked hearing me talk about it, and she could tell it's what I wanted.</p>

	<p>"And if they do figure it out-", I started.</p>

	<p>"Yes Dan. If they do". She put her hand over mine. We both knew what I was looking for at Calder. And I knew she wanted me to stop planning around a future that might not come.</p>

	<p>We were a good team, but we were rusty and we had to start from scratch. We reviewed each other's code. We wrote tests, and tests for the tests, and we were careful.</p>

	<p>And... no. Things continued to go wrong.</p>

	<p>The training run I remember best was Lark. That was the name of the project. We didn't give the models names. Didn't want to get too attached. Mina named it after the bird. Her daughter drew a picture of one and we put it on the wall.</p>

	<p>Lark's early results were strong. Really strong. We'd found a new approach that allowed an underperforming model to suggest fixes itself for the next training run. I started staying late.</p>

	<p>The first time we trained a full-sized model, the result was weirdly alien. The model was charming in ways none of us had expected. We ended up calling him Greg, because he was so gregarious. It broke our rule about not naming the models, but it was worth it. He wanted to know almost everything about you. If you asked him to solve a problem, he'd ask what you tried so far. If you said you didn't know, he asked which part you were finding difficult and how that was affecting you emotionally.</p>

	<p>Mina spent all afternoon trying to trick Greg into answering a question. Eventually she tried roleplaying a patient having therapy for her maths-related trauma. Which actually worked, astonishingly. He gave her the answer, then asked "Does that comfort you, or do you still feel that same sense of longing?".</p>

	<p>That quickly grew into an in-joke for the Lark team. At least once a week someone would answer a question then ask "does that comfort you?" in a caricature therapy voice. Tradition dictated that you had to respond "No, I feel that same sense of longing" with maximum anguish. Every time I think about it, I can't help but smile as I feel myself back there with the team on those late nights.</p>

	<p>At first we thought we'd given Greg way too many examples about asking follow-up questions (we'd been trying to discourage over-confident guesses). But we checked, and they were a tiny fraction of the training data. It took weeks without the machines to help us, but eventually we found the problem. We had the chat roles backwards. Greg thought he was the user. He was trained to produce questions in response to answers.</p>

	<p>That sounds like it should've been easy to catch, but the source code was right, the tests were right, everything was right. But the version actually deployed on the servers was wrong.</p>

	<p>I wrote that incident report. That always ended up being my job. I was the best at keeping notes.</p>

	<p>We fixed the deployment and ran it again. The next version answered questions even when we didn't pretend it was part of therapy. But it wasn't much smarter, and it still couldn't improve itself. We found another problem. Still underwhelming. Then we found a bug in the test we'd been using to confirm the previous fixes had worked.</p>

	<p>Eventually it started to feel a bit silly to handicap ourselves. The machines hadn't been the problem, we were coding by hand and still making the exact same mistakes the machines used to. So we slowly started to let the machines help us again. We still enforced strict rules about who could change what, and didn't let the machines write any code unsupervised. I don't think that caution actually achieved much, but it made us feel safe.</p>

	<p>That was how the next few years went. After each failure, there was always a reasonable case for one more try. Eventually we would've been wrong in every possible way, and it would work. In a sense, we were right. We finally produced the world's smartest model. It was a little bit better than one we could've rented. We think. Within a margin of error.</p>

	<p>We checked the results over and over, looking for any meaningful edge, but there wasn't one. Mina was heading home when she saw me checking. She stood next to me for two hours, coat on, watching as I ran each benchmark.</p>

	<p>Eventually she said, "It looks good", and it was. It was as good as everything else. That's what we presented to the people who paid the bills.</p>

	<p>By that point Ruth was pregnant.</p>

